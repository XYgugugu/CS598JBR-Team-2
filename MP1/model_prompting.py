def prompt_model(dataset, model_name = "deepseek-ai/deepseek-coder-6.7b-base", quantization = True):
    print(f"Working with {model_name} quantization {quantization}...")
    
    # TODO: download the model
    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
    is_instruct = "instruct" in model_name
  
    if quantization:
        # TODO: load the model with quantization
        bnb_config = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_use_double_quant=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.bfloat16,
        )
        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            quantization_config=bnb_config,
            torch_dtype=torch.bfloat16,
            device_map="auto",
            trust_remote_code=True,
        )
    else:
        # TODO: load the model without quantization
        model = AutoModelForCausalLM.from_pretrained(
            model_name,
            torch_dtype=torch.bfloat16,
            device_map="auto",
            trust_remote_code=True,
        )
    model.eval()

    results = []
    results_processed = []
    for case in dataset:
        prompt = case['prompt']
        
        # TODO: prompt the model and get the response
        if is_instruct:
            messages = [{
                "role": "user",
                "content": "Complete the following Python function. Return the complete function "
                           "in a single Python code block, without tests or explanation.\n"
                           f"```python\n{prompt}```",
            }]
            input_ids = tokenizer.apply_chat_template(messages, add_generation_prompt=True, return_tensors="pt").to(model.device)
        else:
            input_ids = tokenizer(prompt, return_tensors="pt").input_ids.to(model.device)
        with torch.no_grad():
            outputs = model.generate(
                input_ids,
                attention_mask=torch.ones_like(input_ids),
                max_length=500,
                do_sample=False,  # greedy decoding, i.e., temperature 0
                eos_token_id=tokenizer.eos_token_id,
                pad_token_id=tokenizer.eos_token_id,
            )
        response = tokenizer.decode(outputs[0][input_ids.shape[1]:], skip_special_tokens=True)
        
        print(f"Task_ID {case['task_id']}:\nPrompt:\n{prompt}\nResponse:\n{response}")
        results.append(dict(task_id=case["task_id"], completion=response))
        
        # TODO: postprocessing may be required to handle extraneous output, fix indentation issues generated by the model, or handle other similar, trivial issues
        import ast
        import re

        def extract_code(text):
            # Take the code inside a markdown block (the one defining the entry point, if any);
            # an unterminated block (response cut off by max_length) runs to the end of the text.
            blocks = re.findall(r"```[a-zA-Z0-9_+-]*[ \t]*\n(.*?)(?:```|$)", text, re.DOTALL)
            if not blocks:
                return text
            for block in blocks:
                if re.search(rf"^\s*def\s+{case['entry_point']}\s*\(", block, re.MULTILINE):
                    return block
            return blocks[0]

        def fix_body_indentation(body, first_line_lost_indent):
            # Map the indentation levels used by the function body (the lines before the first
            # top-level statement) onto multiples of 4 spaces, e.g. 3/7 spaces -> 4/8. The model
            # often drops the indentation of the first line only; in that case the first line
            # belongs to the outermost level used by the following lines.
            lines = body.split("\n")
            end = next((i for i, l in enumerate(lines) if i > 0 and l.strip() and not l[0].isspace()), len(lines))
            head, tail = lines[:end], lines[end:]
            widths = [len(l) - len(l.lstrip()) if l.strip() else None for l in head]
            first = next((i for i, w in enumerate(widths) if w is not None), None)
            rest = [w for i, w in enumerate(widths) if w is not None and i != first]
            if first is not None and first_line_lost_indent and rest and widths[first] < min(rest):
                widths[first] = min(rest)
            level = {w: 4 * (i + 1) for i, w in enumerate(sorted({w for w in widths if w is not None}))}
            head = [" " * level[w] + l.lstrip() if w is not None else "" for l, w in zip(head, widths)]
            return "\n".join(head + tail)

        def indent_whole_body(body):
            # The whole body was generated without indentation: indent every line up to the first
            # statement that clearly starts a new top-level block.
            lines = body.split("\n")
            end = next((i for i, l in enumerate(lines) if re.match(r"(def |class |@|if __name__|print\(|assert )", l)), len(lines))
            return "\n".join(["    " + l if l.strip() else "" for l in lines[:end]] + lines[end:])

        def parse_program(completion):
            # Parse prompt + completion; if it does not compile (e.g., the response was cut off
            # by max_length), drop trailing lines of the completion until it does.
            lines = completion.split("\n")
            for n in range(len(lines), -1, -1):
                candidate = "\n".join(lines[:n]) + "\n"
                try:
                    compile(prompt + candidate, "<completion>", "exec")
                    return candidate, ast.parse(prompt + candidate)
                except SyntaxError:
                    continue
            return None, None

        def clean_program(completion, tree):
            # Keep only top-level imports, definitions and assignments that the entry point
            # (transitively) depends on; drop tests, prints, `if __name__ == ...` blocks and
            # irrelevant functions/classes that the model generated after the solution.
            program_lines = (prompt + completion).split("\n")
            prompt_line_count = prompt.count("\n")
            defs = {}
            for node in tree.body:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    defs.setdefault(node.name, []).append(node)
            needed, stack = set(), [case["entry_point"]]
            while stack:
                name = stack.pop()
                if name in needed or name not in defs:
                    continue
                needed.add(name)
                for node in defs[name]:
                    stack.extend(n.id for n in ast.walk(node) if isinstance(n, ast.Name))
            drop = set()
            for node in tree.body:
                start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])]) - 1
                if node.end_lineno <= prompt_line_count:
                    continue  # never touch the given prompt
                if isinstance(node, (ast.Import, ast.ImportFrom, ast.Assign, ast.AnnAssign)):
                    continue
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.name in needed:
                    continue
                drop.update(range(max(start, prompt_line_count), node.end_lineno))
            kept = [l for i, l in enumerate(program_lines) if i < prompt_line_count or i not in drop]
            return "\n".join(kept)[len(prompt):]

        code = extract_code(response)
        if re.search(rf"^def\s+{case['entry_point']}\s*\(", code, re.MULTILINE):
            # The model re-generated the whole function: append it after the prompt so that it
            # redefines the (docstring-only) function given in the prompt.
            candidates = ["\n" + code]
        else:
            # The model only generated the function body.
            candidates = [code, fix_body_indentation(code, True), indent_whole_body(code), fix_body_indentation(code, False)]
        def is_implemented(tree):
            # The (last) definition of the entry point must have a body beyond its docstring.
            funcs = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == case["entry_point"]]
            if not funcs:
                return False
            body = funcs[-1].body
            has_docstring = isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str)
            return len(body) > int(has_docstring)

        response_processed = code
        for candidate in candidates:
            completion, tree = parse_program(candidate)
            if tree is None or not is_implemented(tree):
                continue
            completion = clean_program(completion, tree)
            try:
                compile(prompt + completion, "<completion>", "exec")
            except SyntaxError:
                continue
            response_processed = completion
            break
        
        results_processed.append(dict(task_id=case["task_id"], completion=response_processed))
    return results, results_processed

def read_jsonl(file_path):
    dataset = []
    with jsonlines.open(file_path) as reader:
        for line in reader: 
            dataset.append(line)
    return dataset

def write_jsonl(results, file_path):
    with jsonlines.open(file_path, "w") as f:
        for item in results:
            f.write_all([item])

if __name__ == "__main__":
    """
    This Python script is to run prompt LLMs for code synthesis.
    Usage:
    `python3 model_prompting.py <input_dataset> <model> <output_file> <output_file_processed> <if_quantization> `|& tee prompt.log

    Inputs:
    - <input_dataset>: A `.jsonl` file, which should be your team's dataset containing 20 HumanEval problems.
    - <model>: Specify the model to use. Options are "deepseek-ai/deepseek-coder-6.7b-base" or "deepseek-ai/deepseek-coder-6.7b-instruct".
    - <output_file>: A `.jsonl` file where the results will be saved.
    - <output_file_processed>: A `.jsonl` file where the processed results will be saved
    - <if_quantization>: Set to 'True' or 'False' to enable or disable model quantization.
    
    Outputs:
    - You can check <output_file> and  <output_file_processed> for detailed information.
    """
    args = sys.argv[1:]
    input_dataset = args[0]
    model = args[1]
    output_file = args[2]
    output_file_processed = args[3]
    if_quantization = args[4] # True or False
    
    if not input_dataset.endswith(".jsonl"):
        raise ValueError(f"{input_dataset} should be a `.jsonl` file!")
    
    if not output_file.endswith(".jsonl"):
        raise ValueError(f"{output_file} should be a `.jsonl` file!")
    
    quantization = True if if_quantization == "True" else False
    
    dataset = read_jsonl(input_dataset)
    results, results_processed = prompt_model(dataset, model, quantization)
    write_jsonl(results, output_file)
    write_jsonl(results_processed, output_file_processed)
